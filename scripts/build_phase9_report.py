"""Phase 9, Steps 9.1–9.4: build reports/phase9/context_and_events_2010-2020.md from saved files only.

Run:  uv run python scripts/build_phase9_report.py
COUNTS AND TIMING ONLY — no prices, no returns, no feature values, nothing linked to what happened after an event
(prompt 23 hard rule: the Phase 9 rules must be pre-registered before anyone looks at outcomes).
"""

import json
import sys
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path

import pandas as pd

from quant_research.data.loader import load_prices, load_prices_with_warmup
from quant_research.news.context import daily, market_context, stock_context
from quant_research.news.events import CATEGORY, EXHIBITS_ONLY, categories, timing, usable_close_day

PROJECT_ROOT = Path(__file__).resolve().parents[1]
SUB = PROJECT_ROOT / "data" / "raw" / "sec" / "submissions"
REPORT = PROJECT_ROOT / "reports" / "phase9" / "context_and_events_2010-2020.md"
COMPANIES = ["AAPL", "MSFT", "KO", "PG", "XOM", "INTC", "T"]
TICKERS = [*COMPANIES, "SPY"]
YEARS = list(range(2010, 2021))
START, END = date(2010, 1, 4), date(2020, 12, 31)
TIMING = ["before open", "during trading", "after close", "non-trading day"]
EVIDENCE = [("AAPL", "2019-10-30"), ("AAPL", "2020-01-28"), ("AAPL", "2020-04-30")]


def load_filings() -> dict[str, tuple[list[dict], dict]]:
    out = {}
    for t in COMPANIES:
        [path] = sorted(SUB.glob(f"{t}_CIK*_8k_to-2020-12-31.json"))
        meta = json.loads(path.with_suffix(".meta.json").read_text())
        out[t] = (json.loads(path.read_text())["filings"], meta)
    return out


def main() -> int:
    data = load_filings()
    out = [
        "# Phase 9 — market context features and SEC 8-K events, 2010–2020 (Steps 9.1–9.4)",
        "",
        "> **Data and features only — COUNTS AND TIMING, no prices, no returns, no feature values, nothing about what",
        "> happened after an event.** The Phase 9 strategy rules are pre-registered first (prompt 24). Generated by",
        "> `scripts/build_phase9_report.py` from saved files. Nothing filed, accepted or dated after 2020-12-31 (D8).",
        "",
        "## 1. Source and fields (Step 9.2)",
        "",
        "SEC EDGAR submissions API `https://data.sec.gov/submissions/CIK##########.json` (free, no key; public",
        "information — cite SEC). Newest ~1,000 filings in `filings.recent`, older ones in the pages listed in",
        "`filings.files` — all followed. **Field names checked in the real JSON:** `form`, `filingDate`,",
        "`acceptanceDateTime`, `items`, `accessionNumber`, `primaryDocument`, `reportDate` (as expected). Forms kept:",
        "8-K and 8-K/A. Same CIKs as Phase 7 (XOM = 0000034088, the 2010–2020 filer).",
        "",
        "| Company | CIK | Older pages followed | Filings read (all forms) | 8-K kept (≤ 2020-12-31) | 8-K dropped (> 2020-12-31, D8) | Of which 2010–2020 |",
        "|---|---|---|---|---|---|---|",
    ]
    for t, (fs, m) in data.items():
        in_period = sum(START.isoformat() <= f["filingDate"] <= END.isoformat() for f in fs)
        out.append(
            f"| {t} | {int(m['endpoint'].split('CIK')[1][:10]):010d} | {len(m['pages_followed'])} | {m['rows_read']:,} | "
            f"{m['8k_kept']} | {m['8k_dropped_after_cutoff']} | {in_period} |"
        )
    out += [
        "",
        "## 2. Timezone evidence (critical)",
        "",
        "`acceptanceDateTime` ends in `Z`. Test: Apple publishes quarterly results after the 16:00 ET close (16:30 ET).",
        "If the field were Eastern time merely labelled `Z`, the raw clock would read 16:30 in summer and winter alike.",
        "It does not — it moves by one hour with daylight saving, so it is **true UTC**; converted to US/Eastern:",
        "",
        "| Filing | Items | Raw acceptanceDateTime | US/Eastern |",
        "|---|---|---|---|",
    ]
    for t, d in EVIDENCE:
        for f in data[t][0]:
            if f["filingDate"] == d and "2.02" in f["items"]:
                out.append(
                    f"| {t} 8-K {f['accessionNumber']} | {f['items']} | `{f['acceptanceDateTime']}` | {f['acceptance_eastern']} |"
                )
    out += [
        "",
        "## 3. Item code → category map (Step 9.3, rule-based, no AI)",
        "",
        "Source: SEC Form 8-K (form SEC 873 (02-25)), https://www.sec.gov/files/form8-k.pdf — Items 1.01–9.01.",
        "",
        "| Item | Category |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in sorted(CATEGORY.items())],
        f"| 9.01 alone | {EXHIBITS_ONLY} (not an event on its own; 9.01 next to other items adds nothing) |",
        "| any other official item | other (code kept) |",
        "| code not on the official list | UNRECOGNISED (code kept, never guessed) |",
        "",
        "## 4. Filings per company × category × year (2010–2020; a filing can count in several categories)",
        "",
    ]
    unrecognised: dict[str, Counter] = defaultdict(Counter)
    timing_count: dict[str, Counter] = defaultdict(Counter)
    forms: dict[str, Counter] = defaultdict(Counter)
    lag: dict[str, Counter] = defaultdict(Counter)
    for t, (fs, _) in data.items():
        table: dict[str, Counter] = defaultdict(Counter)
        for f in fs:
            cats = categories(f["items"])
            year = int(f["filingDate"][:4])
            for c in cats:
                if c.startswith("UNRECOGNISED"):
                    unrecognised[c][year] += 1
            if not 2010 <= year <= 2020:
                continue
            accepted = pd.Timestamp(f["acceptance_eastern"]).to_pydatetime()
            timing_count[t][timing(accepted)] += 1
            forms[t][f["form"]] += 1
            days = (usable_close_day(accepted) - accepted.date()).days
            lag[t][
                "same day" if days == 0 else ("next day" if days == 1 else "2+ calendar days")
            ] += 1
            for c in cats:
                table[c][year] += 1
        out += [
            f"**{t}**",
            "",
            "| Category | " + " | ".join(map(str, YEARS)) + " | Total |",
            "|---|" + "---|" * (len(YEARS) + 1),
        ]
        for c in sorted(table):
            out.append(
                f"| {c} | "
                + " | ".join(str(table[c][y]) for y in YEARS)
                + f" | {sum(table[c].values())} |"
            )
        out.append("")
    out += ["## 5. Unrecognised item codes (all years kept on disk)", ""]
    if unrecognised:
        out += ["| Code | Filings | Years |", "|---|---|---|"]
        for c in sorted(unrecognised):
            ys = unrecognised[c]
            out.append(f"| {c} | {sum(ys.values())} | {min(ys)}–{max(ys)} |")
        out += [
            "",
            "These are the single-number items of the pre-August-2004 Form 8-K (not on today's official list). None",
            "falls in 2010–2020, so the study period is unaffected; they are listed, not mapped.",
        ]
    else:
        out.append("- none")
    out += [
        "",
        "## 6. When filings are accepted (US/Eastern, 2010–2020) and when they become usable",
        "",
        "| Company | 8-K | 8-K/A | Before open (< 09:30) | During trading | After close | Non-trading day | Usable same day | Usable next day | Usable 2+ calendar days later |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for t in COMPANIES:
        tc, fm, lg = timing_count[t], forms[t], lag[t]
        out.append(
            f"| {t} | {fm['8-K']} | {fm['8-K/A']} | "
            + " | ".join(str(tc[k]) for k in TIMING)
            + f" | {lg['same day']} | {lg['next day']} | {lg['2+ calendar days']} |"
        )
    total = Counter()
    for t in COMPANIES:
        total.update(timing_count[t])
    out += [
        f"| **All** | {sum(forms[t]['8-K'] for t in COMPANIES)} | {sum(forms[t]['8-K/A'] for t in COMPANIES)} | "
        + " | ".join(str(total[k]) for k in TIMING)
        + f" | {sum(lag[t]['same day'] for t in COMPANIES)} | {sum(lag[t]['next day'] for t in COMPANIES)} | "
        f"{sum(lag[t]['2+ calendar days'] for t in COMPANIES)} |",
        "",
        "## 7. Availability rule (Step 9.4) — written into DATA_SOURCES §12 and tested",
        "",
        "An event becomes usable for a decision at the **close of the first NYSE trading day D whose close is after its",
        "acceptance time** (US/Eastern; close 16:00, or 13:00 on early-close days) → trade at D+1's open. Accepted",
        "09:00 ET on D → D's close; 16:30 ET on D → D+1's close; weekend / holiday → next trading day's close. An 8-K/A",
        "is its own event at its own acceptance time. Using the real close time (not a fixed 16:00) is stricter on the",
        "few early-close days. Tests: `tests/news/test_events.py` (before open, intraday, after close, weekend, holiday,",
        "early close, DST switch, amendment) and the events spy check `check_events_no_lookahead` (moving any event one",
        "day later never changes an earlier decision; a deliberately leaky decision is caught).",
        "",
        "## 8. Market context features (Step 9.1) — warm-up coverage only (no values)",
        "",
        "Computed point-in-time at each close T from rows ≤ T (split-adjusted as of T; `strategies/indicators.py`).",
        "Market (from SPY): above its 200-day average · 200-day average slope over 20 days · 20-day realised volatility.",
        "Stock: 60-day momentum · 20-day realised volatility · volume ÷ median of the 50 volumes ending at T.",
        "Price history on disk starts 2008-01-02, so every feature has its warm-up before 2010.",
        "",
        "| Ticker | Trading days 2010–2020 | Market: above 200d / slope / vol 20d available | Stock: momentum 60d / vol 20d / volume ratio available |",
        "|---|---|---|---|",
    ]
    for t in TICKERS:
        dev = load_prices_with_warmup(t, date(2008, 1, 1), date(2010, 1, 1), date(2016, 12, 31))
        df = pd.concat(
            [dev, load_prices(t, date(2017, 1, 1), date(2020, 12, 31))], ignore_index=True
        )
        if max(df["date"]) >= date(2021, 1, 1):
            raise SystemExit(f"{t}: data after 2020")
        st = daily(df, stock_context, START, END)
        n = len(st)
        stock = " / ".join(
            str(sum(getattr(s, k) is not None for s in st))
            for k in ("momentum_60d", "volatility_20d", "volume_vs_50d_median")
        )
        if t == "SPY":
            mk = daily(df, market_context, START, END)
            market = " / ".join(
                str(sum(getattr(m, k) is not None for m in mk))
                for k in ("above_200d", "sma200_slope_20d", "volatility_20d")
            )
        else:
            market = "(from SPY)"
        out.append(f"| {t} | {n} | {market} | {stock} |")
    out += [
        "",
        "## 9. Not used",
        "",
        "- VIX, other indices, sector data, analyst estimates, news text: not in our free data set → not used",
        "  (DATA_SOURCES §12). AI labelling of 8-K text = optional exploratory side test later (decision 2026-10-27).",
        "- 8-K text itself is not read; categories come only from the official item codes.",
    ]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"report written: {REPORT.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
