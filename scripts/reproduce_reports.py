"""Regenerate every generated report from the saved records and compare it byte for byte with git (Phase 10.4).

Run:  uv run --all-groups python scripts/reproduce_reports.py       (exit code 1 if any report differs)
Each report-only generator is run; its output is compared with the committed version (git HEAD) and the committed
bytes are then put back, so this script never changes a report. Needs the git-ignored data/ folder (licensed data):
on a fresh clone it stops with a message. Reports that are NOT regenerated here are listed with the reason.
"""

import argparse
import re
import subprocess
import sys
import time
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
# (generator command, report it writes)
GENERATED = [
    (["scripts/validate_initial_dataset.py"], "reports/data_validation/2010-2016_AAPL_XOM.md"),
    (["scripts/validate_phase6_data.py"], "reports/data_validation/phase6_all_stocks_2008-2020.md"),
    (["scripts/validate_final_data.py"], "reports/data_validation/final_2021-2025.md"),
    (["scripts/phase5_comparison.py"], "reports/experiments/phase5_comparison_dev_2010-2016.md"),
    (["scripts/report_validation.py"], "reports/experiments/validation_2017-2020.md"),
    (["scripts/validation_headline.py"], "reports/experiments/validation_headline_2017-2020.md"),
    (["scripts/build_indicators.py"], "reports/screening/indicators_2010-2020.md"),
    (["scripts/build_screening.py"], "reports/screening/screening_2010-2020.md"),
    (["scripts/build_phase9_report.py"], "reports/phase9/context_and_events_2010-2020.md"),
    (["scripts/report_phase9.py"], "reports/experiments/phase9_information_2017-2020.md"),
    (["scripts/ai_label_sample.py", "compare"], "reports/phase9/ai_labels_sample.md"),
    (["scripts/report_final_test.py"], "reports/experiments/FINAL_TEST_2021-2025.md"),
]
# the ONLY tolerated difference: a "generated on <date>" stamp (it records the day the generator ran)
DATE_STAMP = re.compile(rb"(Generated by `[^`]+` on )\d{4}-\d{2}-\d{2}")
NOT_REGENERATED = {
    "reports/runs/s0_dev_2010-2016.md": "written by scripts/run_s0_dev.py --report, which RUNS the backtests again "
    "(new run ids and times in the report) — not a report-only step",
    "reports/experiments/s1_s2_dev_2010-2016.md": "written by scripts/run_s1_s2_dev.py together with new runs",
    "reports/experiments/s3_s4_dev_2010-2016.md": "written by scripts/run_s3_s4_dev.py together with new runs",
    "reports/accounting/golden_scenario.md": "hand-written; every number is asserted by "
    "tests/accounting/test_golden_scenario.py",
    "reports/RESULTS_SUMMARY.md": "hand-written summary; every number cites a generated report",
    "reports/ENVIRONMENT.md": "written by scripts/record_environment.py (versions, not results)",
}


def committed(path: str) -> bytes:
    return subprocess.run(
        ["git", "show", f"HEAD:{path}"], cwd=PROJECT_ROOT, check=True, capture_output=True
    ).stdout


def main() -> int:
    argparse.ArgumentParser(description=__doc__.splitlines()[0]).parse_args()
    if not (PROJECT_ROOT / "data" / "runs").exists():
        print(
            "data/ is not present (git-ignored licensed data, e.g. a fresh clone) — nothing to reproduce"
        )
        return 0
    rows, failed = [], 0
    for command, report in GENERATED:
        path = PROJECT_ROOT / report
        before = committed(report)
        started = time.time()
        proc = subprocess.run(
            [sys.executable, *command],
            cwd=PROJECT_ROOT,
            capture_output=True,
            text=True,
            check=False,
        )
        seconds = time.time() - started
        after = path.read_bytes() if path.exists() else b""
        path.write_bytes(before)  # always put the committed version back
        if proc.returncode != 0:
            status = f"GENERATOR FAILED (exit {proc.returncode}): {proc.stdout.strip().splitlines()[-1:]}"
        elif after == before:
            status = "identical"
        elif DATE_STAMP.sub(rb"\1DATE", after) == DATE_STAMP.sub(rb"\1DATE", before):
            status = "identical apart from its 'generated on' date stamp"
        else:
            status = "DIFFERS"
        failed += not status.startswith("identical")
        rows.append((report, " ".join(command), status, seconds))
    width = max(len(r) for r, *_ in rows)
    for report, command, status, seconds in rows:
        print(f"{report:<{width}}  {seconds:5.1f}s  {status}  ({command})")
    exact = sum(s == "identical" for _, _, s, _ in rows)
    print(
        f"\n{exact}/{len(rows)} byte-identical to git HEAD; {len(rows) - failed - exact} identical apart from the "
        f"generation date stamp; {failed} different"
    )
    print("Not regenerated (with reason):")
    for report, why in NOT_REGENERATED.items():
        print(f"  - {report}: {why}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
