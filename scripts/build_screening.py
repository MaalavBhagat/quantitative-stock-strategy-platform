"""Phase 7, Steps 7.3–7.5: build reports/screening/screening_2010-2020.md from saved files only.

Run from the project folder:  uv run python scripts/build_screening.py
- Quality scores per research/SCREENING_METHOD.md v1 (fixed before any score, commit f66e267) for each 31 Dec
  2009 (development comparison only) and 2010 … 2020 — point-in-time (10-K filed before the as-of date).
- Selection-bias section (7.4) and company comparison (7.5) from the saved run records (summaries only).
- Descriptive only. No new strategy, no tuning. Nothing filed or dated after 2020-12-31 (D8).
"""

import json
import statistics
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

import pandas as pd

from quant_research.data.loader import load_prices, load_prices_with_warmup
from quant_research.screening.score import INPUTS, indicators_on, quality_scores, spearman
from quant_research.screening.trading import year_indicators

sys.path.insert(0, str(Path(__file__).resolve().parent))
from report_validation import DEV_COMMITS, LABELS, STRATEGIES, setting_of

PROJECT_ROOT = Path(__file__).resolve().parents[1]
SEC_DIR = PROJECT_ROOT / "data" / "raw" / "sec"
RUNS = PROJECT_ROOT / "data" / "runs"
REPORT = PROJECT_ROOT / "reports" / "screening" / "screening_2010-2020.md"
COMPANIES = ["AAPL", "MSFT", "KO", "PG", "XOM", "INTC", "T"]
TICKERS = [*COMPANIES, "SPY"]
AS_OF = [date(y, 12, 31) for y in range(2009, 2021)]
DEV_AS_OF, VAL_AS_OF = date(2009, 12, 31), date(2016, 12, 31)
METHOD_COMMIT = "f66e267"
PROFILE = [  # (key, label)
    ("volatility_annualised", "volatility"),
    ("median_dollar_volume_usd", "median $ volume"),
    ("median_daily_range", "daily range"),
    ("dividend_yield_ttm", "dividend yield"),
]


def pct(x: float | None, signed: bool = False) -> str:
    if x is None:
        return "—"
    return f"{x:+.2%}" if signed else f"{x:.2%}"


def pts(x: float) -> str:
    return f"{x * 100:+.1f}"


def load_sec(t: str) -> dict:
    [path] = sorted(SEC_DIR.glob(f"{t}_CIK*_filed-to-2020-12-31.json"))
    return json.loads(path.read_text())


def run_returns() -> tuple[dict, dict, dict, dict]:
    """Validation MAIN + development: {(label, ticker): {setting: total return}} and {ticker: S0 total return}."""
    val, val_s0, dev, dev_s0 = defaultdict(dict), {}, defaultdict(dict), {}
    for path in sorted((RUNS / "validation" / "main").glob("*/run.json")):
        r = json.loads(path.read_text())
        s, cfg = r["summary"], r["config"]
        ret = float(s["last_close_value_usd"]) / float(s["start_cash_usd"]) - 1
        label = LABELS[cfg["strategy"]]
        if label == "S0":
            val_s0[cfg["ticker"]] = ret
        else:
            val[(label, cfg["ticker"])][setting_of(cfg)] = ret
    for path in sorted(RUNS.glob("*/run.json")):
        r = json.loads(path.read_text())
        commit, label = str(r["git_commit"])[:7], LABELS[r["config"]["strategy"]]
        if commit not in DEV_COMMITS or label not in DEV_COMMITS[commit]:
            continue
        s = r["summary"]
        ret = float(s["last_close_value_usd"]) / float(s["start_cash_usd"]) - 1
        if label == "S0":
            dev_s0[r["config"]["ticker"]] = ret
        else:
            dev[(label, r["config"]["ticker"])][setting_of(r["config"])] = ret
    return val, val_s0, dev, dev_s0


def median_excess(by: dict, s0: dict, label: str, t: str) -> float | None:
    rets = by.get((label, t))
    return None if not rets else statistics.median(r - s0[t] for r in rets.values())


def main() -> int:
    cfs = {t: load_sec(t) for t in COMPANIES}
    prices = {}
    for t in TICKERS:
        dev = load_prices_with_warmup(t, date(2008, 1, 1), date(2010, 1, 1), date(2016, 12, 31))
        prices[t] = pd.concat(
            [dev, load_prices(t, date(2017, 1, 1), date(2020, 12, 31))], ignore_index=True
        )
        if max(prices[t]["date"]) >= date(2021, 1, 1):
            raise SystemExit(f"{t}: data after 2020")
    scores, used = {}, {}
    for d in AS_OF:
        inputs = {}
        for t in COMPANIES:
            fy, ind = indicators_on(cfs[t], d)
            inputs[t], used[(t, d)] = ind, fy
        scores[d] = quality_scores(inputs)
    profile = {(t, d): year_indicators(prices[t], d.year) for t in TICKERS for d in AS_OF}
    val, val_s0, dev, dev_s0 = run_returns()
    if len(val_s0) != 8 or sum(len(v) for v in val.values()) != 8 * 70:
        raise SystemExit("unexpected number of validation MAIN runs")

    out = [
        "# Phase 7 screen 2010–2020 (Steps 7.3–7.5)",
        "",
        "> **Descriptive screen — not a recommendation, not financial advice.** A transparent, reproducible SCREEN of",
        "> 7 companies chosen with hindsight; nothing in it has been tested out of sample. Strategy results are",
        "> SIMULATED, HISTORICAL. Generated by `scripts/build_screening.py` from saved files; no number typed by hand.",
        "",
        "## 1. Method (fixed before any score: research/SCREENING_METHOD.md v1, commit "
        + METHOD_COMMIT
        + ")",
        "",
        "Quality score = average of 5 rank sub-scores (best 1.0 … worst 0.0 among the companies with that input):",
        "ROA ↑ · FCF margin ↑ · liabilities ÷ assets ↓ · current ratio ↑ · EPS-growth std dev ↓. At least 4 of 5",
        "inputs, else NOT SCORED. MISSING / CONFLICT inputs count as missing. Point-in-time: on 31 Dec of year Y, the",
        "latest 10-K filed BEFORE that date, values as known before it. 31 Dec 2009 is used only for the",
        "development comparison. The trading profile is reported, NOT scored.",
        "",
        "## 2. Quality scores per as-of date",
        "",
        "| As of | " + " | ".join(COMPANIES) + " |",
        "|---|" + "---|" * len(COMPANIES),
    ]
    for d in AS_OF:
        cells = []
        for t in COMPANIES:
            q = scores[d][t].quality
            cells.append("NOT SCORED" if q is None else f"{q:.2f}")
        out.append(f"| {d} | " + " | ".join(cells) + " |")
    out += ["", "10-K behind each score (fiscal-year end / filed):", ""]
    out += ["| As of | " + " | ".join(COMPANIES) + " |", "|---|" + "---|" * len(COMPANIES)]
    for d in AS_OF:
        out.append(
            f"| {d} | "
            + " | ".join(
                "none" if used[(t, d)] is None else f"{used[(t, d)].end} / {used[(t, d)].filed}"
                for t in COMPANIES
            )
            + " |"
        )
    out += ["", "## 3. Why each score (built from the sub-scores)", ""]
    for d in AS_OF:
        out.append(f"**As of {d}**")
        out.append("")
        ranked = sorted(
            COMPANIES,
            key=lambda t: -(scores[d][t].quality if scores[d][t].quality is not None else -1),
        )
        for t in ranked:
            sc = scores[d][t]
            head = "NOT SCORED" if sc.quality is None else f"{sc.quality:.2f}"
            subs = ", ".join(f"{INPUTS[k][0]} {v:.2f}" for k, v in sc.subscores.items())
            out.append(
                f"- **{head}** — {sc.why}" + (f" Sub-scores: {subs}." if sc.subscores else "")
            )
        out.append("")

    # ---------- 7.4 selection bias ----------
    out += [
        "## 4. Selection bias (Step 7.4)",
        "",
        "- **Hindsight in the stock list.** The 8 stocks were chosen in 2026 (research/INITIAL_UNIVERSE.md, v2",
        "  2026-10-17) by role, with their history already known. All are **survivors**: listed and trading today.",
        "  Buy-and-hold (S0) total return, USD, simulated:",
        "",
        "| Stock | S0 development 2010–2016 | S0 validation 2017–2020 |",
        "|---|---|---|",
    ]
    for t in TICKERS:
        out.append(f"| {t} | {pct(dev_s0.get(t))} | {pct(val_s0[t])} |")
    out += [
        "",
        "  (Development S0 was run only for AAPL and XOM.) Companies that failed or were delisted in these years are",
        "  not in the list, so any 'buy the dip' result here is likely too kind (a dip in a failing company may never",
        "  recover).",
        "- **Point-in-time data.** Scores use only 10-K facts filed strictly before the as-of date and prices up to it.",
        "  Tests: `tests/screening/test_fundamentals.py::test_fact_filed_on_day_t_is_not_usable_on_t`,",
        "  `::test_restatement_used_only_from_the_later_filing_date`, `tests/screening/test_score.py::",
        "  test_latest_10k_strictly_before_as_of`, `::test_indicators_on_uses_values_known_before_as_of`; prices:",
        "  the look-ahead spy tests of Phase 4. Facts filed after 2020-12-31 were dropped at download (D8).",
        "- **A ticker is not a company over time.** SEC's ticker list today maps XOM to ExxonMobil Holdings Corp",
        "  (CIK 2115436, nothing filed before 2021); the 2010–2020 filer is EXXON MOBIL CORP, CIK 34088",
        "  (DATA_SOURCES §11). A screen built from today's ticker list would silently get the wrong company.",
        "- **Delisted coverage is partial** (Step 2.3): Tiingo lists 3,019 US stocks with an end date before 2020, but",
        "  Lehman / Enron / WaMu were not found under the symbols checked, and downloading delisted price history is",
        "  untested (DATA_SOURCES §8).",
        "- **What a fair universe would need** (not available from our free data — a LIMITATION, not fixed):",
        "  point-in-time index membership (e.g. who was in the S&P 500 on each date), prices and filings for companies",
        "  that were later delisted, merged or bankrupt, and a ticker ↔ company history.",
        "",
    ]

    # ---------- 7.5 compare companies ----------
    out += [
        "## 5. Compare companies (Step 7.5) — descriptive only",
        "",
        "Median excess = median over a strategy's settings of (strategy total return − S0 total return), percentage",
        "points, USD, MAIN settings. Profile and quality score are as of the START of each period: 31 Dec 2016 for",
        "validation 2017–2020 (all 8 stocks); 31 Dec 2009 for development 2010–2016 (AAPL and XOM only were run).",
        "",
        "**Profile + quality at the period starts**",
        "",
        "| Stock | As of | Volatility | Median $ volume (US$ m) | Daily range | Dividend yield | Quality score |",
        "|---|---|---|---|---|---|---|",
    ]
    for d, ts in ((DEV_AS_OF, ["AAPL", "XOM"]), (VAL_AS_OF, TICKERS)):
        for t in ts:
            p = profile[(t, d)]
            q = scores[d][t].quality if t in COMPANIES else None
            qs = "fund" if t == "SPY" else ("NOT SCORED" if q is None else f"{q:.2f}")
            out.append(
                f"| {t} | {d} | {pct(p.volatility_annualised)} | {p.median_dollar_volume_usd / 1e6:,.0f} | "
                f"{pct(p.median_daily_range)} | {pct(p.dividend_yield_ttm)} | {qs} |"
            )
    out += [
        "",
        "**Median excess vs S0 (pp)**",
        "",
        "| Strategy | Period | " + " | ".join(TICKERS) + " |",
        "|---|---|" + "---|" * len(TICKERS),
    ]
    for label in STRATEGIES:
        dev_cells = [
            pts(m) if (m := median_excess(dev, dev_s0, label, t)) is not None else "—"
            for t in TICKERS
        ]
        val_cells = [pts(median_excess(val, val_s0, label, t)) for t in TICKERS]
        out.append(f"| {label} | dev 2010–16 | " + " | ".join(dev_cells) + " |")
        out.append(f"| {label} | val 2017–20 | " + " | ".join(val_cells) + " |")

    # Spearman
    out += [
        "",
        "## 6. Rank correlation (Spearman) — profile at 31 Dec 2016 vs validation median excess",
        "",
        "> **8 data points (7 for the quality score — SPY has none). No significance test is claimed. This is NOT",
        "> evidence that any profile helps; with so few points a strong-looking number can easily be chance.**",
        "",
        "| Strategy | " + " | ".join(lbl for _, lbl in PROFILE) + " | quality score (7) |",
        "|---|" + "---|" * (len(PROFILE) + 1),
    ]
    corr = {}
    for label in STRATEGIES:
        ex = {t: median_excess(val, val_s0, label, t) for t in TICKERS}
        cells = []
        for key, lbl in PROFILE:
            xs = [getattr(profile[(t, VAL_AS_OF)], key) for t in TICKERS]
            try:
                corr[(label, lbl)] = spearman(xs, [ex[t] for t in TICKERS])
                cells.append(f"{corr[(label, lbl)]:+.2f}")
            except ValueError as exc:
                cells.append(f"n/a ({exc})")
        qs = [
            (scores[VAL_AS_OF][t].quality, ex[t])
            for t in COMPANIES
            if scores[VAL_AS_OF][t].quality is not None
        ]
        try:
            cells.append(f"{spearman([a for a, _ in qs], [b for _, b in qs]):+.2f} (n={len(qs)})")
        except ValueError as exc:
            cells.append(f"n/a ({exc})")
        out.append(f"| {label} | " + " | ".join(cells) + " |")

    # Q4.11
    least_bad = []
    for label in STRATEGIES:
        for t in TICKERS:
            m = median_excess(val, val_s0, label, t)
            if m > 0:
                dm = median_excess(dev, dev_s0, label, t)
                least_bad.append((label, t, m, dm))
    out += [
        "",
        "## 7. Q4.11 — what kind of company does it fit? (plain words)",
        "",
        "**No stock type was found where any strategy reliably beat buy-and-hold.** Every strategy was REJECTED on",
        "validation (reports/experiments/validation_2017-2020.md §1), and no positive case below is confirmed in",
        "both periods.",
        "",
        "The least-bad cases — validation median excess above 0 — with their profile at 31 Dec 2016:",
        "",
        "| Strategy | Stock | Val median excess (pp) | Dev median excess (pp) | S0 validation | Volatility | Dividend yield | Quality |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for label, t, m, dm in sorted(least_bad, key=lambda x: -x[2]):
        p = profile[(t, VAL_AS_OF)]
        q = scores[VAL_AS_OF][t].quality if t in COMPANIES else None
        out.append(
            f"| {label} | {t} | {pts(m)} | {'not run' if dm is None else pts(dm)} | {pct(val_s0[t])} | "
            f"{pct(p.volatility_annualised)} | {pct(p.dividend_yield_ttm)} | "
            f"{'fund' if t == 'SPY' else ('NOT SCORED' if q is None else f'{q:.2f}')} |"
        )
    down = sorted({t for _, t, _, _ in least_bad if val_s0[t] < 0}, key=TICKERS.index)
    up = sorted({t for _, t, _, _ in least_bad if val_s0[t] >= 0}, key=TICKERS.index)
    both = [
        (label, t)
        for label in STRATEGIES
        for t in ("AAPL", "XOM")
        if median_excess(val, val_s0, label, t) > 0 and median_excess(dev, dev_s0, label, t) > 0
    ]
    dev_pos = [
        f"{label} {t} ({pts(median_excess(dev, dev_s0, label, t))})"
        for label in STRATEGIES
        for t in ("AAPL", "XOM")
        if median_excess(dev, dev_s0, label, t) > 0
    ]
    out += [
        "",
        f"What the numbers show (descriptive): {len(least_bad)} of {len(STRATEGIES) * len(TICKERS)} strategy–stock",
        f"pairs are above 0 in validation. Stocks whose own buy-and-hold FELL in 2017–2020: {', '.join(down) or 'none'};",
        f"stocks whose buy-and-hold ROSE: {', '.join(up) or 'none'} — so 'it works on falling stocks' does not cover",
        "every case, and whether a stock will fall is only known afterwards. Pairs above 0 in BOTH development and",
        f"validation (only AAPL and XOM were run in both): {len(both)}"
        + (f" ({', '.join(f'{a} {b}' for a, b in both)})." if both else "."),
        f"Development positives that did not repeat in validation: {', '.join(dev_pos) or 'none'}. The profile",
        "correlations in §6 rest on 8 points and are not evidence. **Why this is not a recommendation:** a handful",
        "of pairs out of 40, one validation period, survivors only, no out-of-sample test of any profile rule, and",
        "the 'fit' is defined by the outcome itself.",
        "",
        "Any idea this suggests is recorded as an UNTESTED hypothesis in research/IDEAS_FOR_LATER.md — no strategy was",
        "created or tuned from it (pre-registration rule).",
        "",
        "## 8. Data limitations",
        "",
        "- Only 7 scored companies — ranks among 7 are coarse; a 0.5 sub-score means 'middle of 7', nothing more.",
        "- Companies scored per as-of date: "
        + ", ".join(
            f"{d.year} {sum(scores[d][t].quality is not None for t in COMPANIES)}" for d in AS_OF
        )
        + ". On 31 Dec 2009 only AAPL had a 10-K in SEC's XBRL data, so its score is the neutral 0.5 of the",
        "  'only one company' rule — it describes nothing; the development comparison therefore has no real score.",
        "- FY2020 10-Ks filed in 2021 are not used (D8), so 31 Dec 2020 uses FY2019 for KO, XOM, INTC, T.",
        "- CONFLICT (PG FY2014, XOM FY2019 revenue) and MISSING (T FY2016 net income) inputs are left out, never filled;",
        "  INTC liabilities use a labelled ASSUMPTION (no non-controlling interest) — reports/screening/",
        "  indicators_2010-2020.md §4.",
        "- Spreads are not available in free data; the trading profile has no spread measure.",
    ]
    REPORT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"report written: {REPORT.relative_to(PROJECT_ROOT)} ; least-bad pairs: {len(least_bad)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
