"""Headline numbers for reports/RESULTS_SUMMARY.md, computed from the saved VALIDATION records (never typed by hand).

Run:  uv run python scripts/validation_headline.py
Reuses scripts/report_validation.py (same loader, same pre-registered verdict code).
Writes reports/experiments/validation_headline_2017-2020.md — summary numbers only.
SIMULATED, HISTORICAL, VALIDATION PERIOD 2017–2020.
"""

import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from report_validation import STRATEGIES, TICKERS, checks, load_runs, table, verdicts

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUT = PROJECT_ROOT / "reports" / "experiments" / "validation_headline_2017-2020.md"


def main() -> int:
    runs = load_runs()
    problems = checks(runs)
    if problems:
        print("STOP —", problems)
        return 1
    v = verdicts(runs)
    by, s0 = table(runs, "main")
    lines = [
        "# Validation 2017–2020 — headline numbers (for RESULTS_SUMMARY.md)",
        "",
        "> SIMULATED, HISTORICAL, VALIDATION PERIOD 2017–2020. Generated by `scripts/validation_headline.py` from the",
        "> same 3,976 saved records and the same verdict code as reports/experiments/validation_2017-2020.md.",
        "",
        "## H1. Per strategy (MAIN settings, all 8 stocks × all settings)",
        "",
        (
            "| Strategy | Verdict | R1 (stocks beating S0, of 8) | Median excess vs S0 (pp) | Runs stranded at end | "
            "Median % days fully in cash |"
        ),
        "|---|---|---|---|---|---|",
    ]
    for label in STRATEGIES:
        rs = [r for t in TICKERS for r in by[(label, t)].values()]
        ex = [r.total_return - s0[r.ticker].total_return for r in rs]
        stranded = sum(r.stranded for r in rs)
        lines.append(
            f"| {label} | {v[label]['verdict']} | {v[label]['r1']} | {statistics.median(ex) * 100:+.1f} | "
            f"{stranded}/{len(rs)} ({stranded / len(rs):.0%}) | {statistics.median(r.days_in_cash for r in rs):.0%} |"
        )
    lines += [
        "",
        "## H2. S0 buy-and-hold in USD vs AUD (MAIN; AUD 10,000 in, RBA rate, Stake 0.55% FX in and out)",
        "",
        "| Stock | USD total return | AUD total return | AUD/USD rate at start (day) | at end (day) |",
        "|---|---|---|---|---|",
    ]
    for t in TICKERS:
        b = s0[t]
        s = b.record["summary"]
        aud = b.final_aud / float(s["initial_aud"]) - 1
        lines.append(
            f"| {t} | {b.total_return:.2%} | {aud:.2%} | {s['usd_per_aud_start']} ({s['usd_per_aud_start_for_day']}) | "
            f"{s['usd_per_aud_end']} ({s['usd_per_aud_end_for_day']}) |"
        )
    lines += [
        "",
        "AUD return = final AUD after the end conversion (liquidation value, 0.55% FX) ÷ AUD 10,000 − 1.",
        "USD return = value at the last close ÷ start cash in USD − 1 (as in all reports).",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"written: {OUT.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    from _help import handle_help  # --help: describe and exit, do nothing else

    handle_help(__doc__)
    sys.exit(main())
