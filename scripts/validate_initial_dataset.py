"""Phase 2, Step 2.3: validate the initial dataset and write the report.

Run:  uv run --group crosscheck python scripts/validate_initial_dataset.py
Reads the saved Tiingo files (no Tiingo calls), cross-checks against cached Yahoo data
(downloads once if not cached), summarises Tiingo's supported-tickers file if present,
and writes reports/data_validation/2010-2016_AAPL_XOM.md.
The report contains counts, dates and % differences only — no price series (licence).
Exit code 1 if any check returned ERROR.
"""

import json
import logging
import sys
from datetime import date, datetime
from pathlib import Path
from typing import Any

import pandas as pd

from quant_research.data.crosscheck import crosscheck, load_or_fetch_yahoo
from quant_research.data.validation import (
    Severity,
    ValidationReport,
    load_raw_csv,
    validate_prices,
)

PROJECT_ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = PROJECT_ROOT / "data" / "raw" / "tiingo"
YAHOO_CACHE = PROJECT_ROOT / "data" / "cache" / "yfinance"
TICKERS_ZIP = PROJECT_ROOT / "data" / "reference" / "tiingo" / "supported_tickers.zip"
REPORT = PROJECT_ROOT / "reports" / "data_validation" / "2010-2016_AAPL_XOM.md"
TICKERS = ["AAPL", "XOM"]
START = date(2010, 1, 1)
END = date(2016, 12, 31)
US_EXCHANGES = {"NYSE", "NASDAQ", "NYSE ARCA", "NYSE MKT", "AMEX", "BATS", "NYSE NAT"}
KNOWN_FAILURES = ["LEH", "LEHMQ", "ENRNQ", "WAMUQ"]  # looked up by symbol only

logger = logging.getLogger("validate_initial_dataset")


def survivorship_summary(path: Path) -> dict[str, Any] | None:
    """Counts from Tiingo's supported_tickers.zip (official docs link in DATA_SOURCES.md)."""
    if not path.exists():
        return None
    df = pd.read_csv(path, dtype=str, keep_default_na=False)
    stocks = df[
        (df["assetType"] == "Stock")
        & (df["priceCurrency"] == "USD")
        & (df["exchange"].isin(US_EXCHANGES))
    ]
    end = pd.to_datetime(stocks["endDate"], errors="coerce")
    return {
        "file_modified": datetime.fromtimestamp(path.stat().st_mtime).date(),
        "columns": list(df.columns),
        "total_rows": len(df),
        "asset_types": df["assetType"].value_counts().to_dict(),
        "us_usd_stocks": len(stocks),
        "us_usd_stocks_end_before_2020": int((end < "2020-01-01").sum()),
        "unparsable_end_dates": int(end.isna().sum()),
        "known_failures_found": [t for t in KNOWN_FAILURES if t in set(df["ticker"].str.upper())],
    }


def pct(x: float) -> str:
    return f"{x:.4%}"


def issues_table(reports: list[ValidationReport]) -> list[str]:
    lines = ["| Ticker | Date | Check | Severity | Message |", "|---|---|---|---|---|"]
    for report in reports:
        for issue in sorted(report.issues, key=lambda i: (i.severity != Severity.ERROR, i.check)):
            msg = issue.message.replace("|", "/")
            lines.append(
                f"| {issue.ticker} | {issue.date or '—'} | {issue.check} | "
                f"{issue.severity.value} | {msg} |"
            )
    return lines


def build_report(
    reports: list[ValidationReport],
    checks: dict[str, dict[str, Any]],
    metas: dict[str, dict[str, Any]],
    survivorship: dict[str, Any] | None,
) -> str:
    out = [
        "# Data validation — AAPL + XOM, 2010-01-01 → 2016-12-31 (Phase 2, Step 2.3)",
        "",
        (
            f"Generated by `scripts/validate_initial_dataset.py` on {date.today()}. "
            "Counts, dates and % differences only — no price series (Tiingo licence: internal use)."
        ),
        "Severity: ERROR = run must stop · WARNING = logged, allowed · INFO = noted.",
        "",
        "## 1. Summary per ticker",
        "",
        "| Ticker | Rows | NYSE sessions | ERROR | WARNING | INFO | Tiingo download (UTC) | Code commit |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in reports:
        m = metas[r.ticker]
        out.append(
            f"| {r.ticker} | {r.stats['rows']} | {r.stats['expected_sessions']} | "
            f"{r.count(Severity.ERROR)} | {r.count(Severity.WARNING)} | {r.count(Severity.INFO)} | "
            f"{m.get('downloaded_at_utc')} | {str(m.get('git_commit'))[:7]} |"
        )
    out += [
        "",
        (
            "Calendar: `exchange_calendars` XNYS (D4). Raw `date` from Tiingo looked like "
            f"`{metas[TICKERS[0]].get('raw_date_example')}` (time part dropped; any non-midnight "
            "time would fail loudly)."
        ),
        "",
        "## 2. Issues",
        "",
        *issues_table(reports),
        "",
        "## 3. Adjusted vs raw prices (where the gap comes from)",
        "",
        (
            "Ratio r = close_adj / close_raw. It changed only on dividend or split ex-dates "
            "(any other change would be a WARNING above)."
        ),
        "",
        (
            "| Ticker | Gap growth inside table | from splits | from dividends | Gap after table end "
            "| Dividends-only estimate after end | Implied |"
        ),
        "|---|---|---|---|---|---|---|",
    ]
    for r in reports:
        s = r.stats
        out.append(
            f"| {r.ticker} | ×{s['gap_factor_in_table']:.4f} | ×{s['gap_from_splits_in_table']:.4f} "
            f"| ×{s['gap_from_dividends_in_table']:.4f} | ×{s['gap_after_table_end']:.4f} "
            f"| ×{s.get('expected_dividends_only_after_end', float('nan')):.4f} "
            f"| {s.get('implied_later_split', '—')} |"
        )
    out += [
        "",
        (
            "The after-end estimate assumes dividends continue at the in-table yearly rate until the "
            "download date — a rough estimate, not a fact."
        ),
        "",
        "## 4. Cross-check with Yahoo Finance (yfinance, `auto_adjust=False`)",
        "",
    ]
    for ticker, c in checks.items():
        days, b, cl, dv, sp = (
            c["trading_days"],
            c["basis"],
            c["closes"],
            c["dividends"],
            c["splits"],
        )
        segs = "; ".join(
            f"{s['from']}→{s['to']}: Yahoo/Tiingo = {s['explained_as']} "
            f"(off by {s['rel_diff']:.1e})"
            for s in b["segments"]
        )
        worst = ", ".join(f"{d} {v:+.3%}" for d, v in cl["worst"][:5])
        out += [
            f"**{ticker}**",
            (
                f"- Trading days: Tiingo {days['tiingo_days']}, Yahoo {days['yahoo_days']}; "
                f"only in Tiingo: {len(days['only_tiingo'])}, only in Yahoo: {len(days['only_yahoo'])}."
            ),
            (
                f"- Basis: Yahoo close split-adjusted = {b['yahoo_close_is_split_adjusted']}; "
                f"later split implied by Yahoo's basis: {b['later_split_ratio_implied']}. {segs}."
            ),
            (
                f"- Closes (Yahoo converted to raw basis): max |diff| {pct(cl['max_abs_pct'])}, "
                f"median {pct(cl['median_abs_pct'])}, days over 0.5%: {cl['count_over_threshold']}. "
                f"Largest: {worst}."
            ),
            "- Close differences over 0.5%, tested against the data: "
            + (
                "; ".join(
                    f"{n['date']} {n['pct']:+.3%} → {n['note']}"
                    for n in c["close_differences_explained"]
                )
                or "none"
            )
            + ".",
            (
                f"- Dividends: Tiingo {dv['tiingo_count']}, Yahoo {dv['yahoo_count']}; only Tiingo "
                f"{dv['only_tiingo']}, only Yahoo {dv['only_yahoo']}; amounts max |diff| "
                f"{pct(dv.get('max_abs_pct', float('nan')))}, over 0.5%: "
                f"{dv.get('count_over_threshold', 0)}."
            ),
            (
                f"- Splits: Tiingo {[(str(d), f) for d, f in sp['tiingo']]}, Yahoo "
                f"{[(str(d), f) for d, f in sp['yahoo']]}; same dates and ratios: "
                f"{sp['same_dates_and_ratios']}."
            ),
            "",
        ]
    out += ["## 5. Survivorship check (Tiingo supported-tickers list)", ""]
    if survivorship is None:
        out.append("supported_tickers.zip not downloaded — finding: unclear.")
    else:
        s = survivorship
        out += [
            (
                "Source: official Tiingo EOD docs link "
                "<https://apimedia.tiingo.com/docs/tiingo/daily/supported_tickers.zip> "
                f"(file dated {s['file_modified']}). Docs describe it as current coverage plus "
                "reserved symbols; they do not say whether delisted tickers are included."
            ),
            "",
            (
                f"- Columns: {', '.join(s['columns'])}. Total rows: {s['total_rows']} "
                f"({', '.join(f'{k} {v}' for k, v in s['asset_types'].items())})."
            ),
            (
                f"- US-exchange USD stocks: {s['us_usd_stocks']}; with endDate before 2020-01-01: "
                f"**{s['us_usd_stocks_end_before_2020']}** (unparsable endDates: "
                f"{s['unparsable_end_dates']})."
            ),
            (
                f"- Known failed companies looked up by symbol ({', '.join(KNOWN_FAILURES)}): found "
                f"{s['known_failures_found'] or 'none'}."
            ),
            (
                "- Reading: the list DOES contain thousands of stocks that stopped trading, but some "
                "well-known failures are not there under the symbols checked. Coverage of delisted "
                "stocks looks partial. Whether their price history is downloadable was NOT tested "
                "(no extra API calls)."
            ),
        ]
    return "\n".join(out) + "\n"


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    reports, checks, metas = [], {}, {}
    for ticker in TICKERS:
        stem = f"{ticker}_{START}_{END}"
        df = load_raw_csv(RAW_DIR / f"{stem}.csv")
        meta = json.loads((RAW_DIR / f"{stem}.meta.json").read_text())
        meta["raw_date_example"] = meta.get("raw_date_example")
        downloaded = datetime.fromisoformat(meta["downloaded_at_utc"]).date()
        report = validate_prices(df, ticker, START, END, downloaded=downloaded)
        reports.append(report)
        metas[ticker] = meta
        checks[ticker] = crosscheck(df, load_or_fetch_yahoo(ticker, START, END, YAHOO_CACHE))
        print(
            f"{ticker}: {report.count(Severity.ERROR)} ERROR, "
            f"{report.count(Severity.WARNING)} WARNING, {report.count(Severity.INFO)} INFO"
        )
        for issue in report.issues:
            if issue.severity != Severity.INFO:
                print(f"  {issue.severity.value} {issue.date} {issue.check}: {issue.message}")
    survivorship = survivorship_summary(TICKERS_ZIP)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(build_report(reports, checks, metas, survivorship), encoding="utf-8")
    print(f"report written: {REPORT.relative_to(PROJECT_ROOT)}")
    return 1 if any(r.has_errors for r in reports) else 0


if __name__ == "__main__":
    sys.exit(main())
