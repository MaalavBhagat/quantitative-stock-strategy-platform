"""Write reports/ENVIRONMENT.md: Python, uv, OS and every installed package version (Phase 10, Step 10.4).

Run:  uv run --all-groups python scripts/record_environment.py
Versions only — no data, no paths outside the project, no secrets. The authoritative pins are in uv.lock.
"""

import argparse
import importlib.metadata
import platform
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
REPORT = PROJECT_ROOT / "reports" / "ENVIRONMENT.md"
KEY = ["pandas", "numpy", "httpx", "exchange-calendars", "xlrd", "pyyaml", "python-dotenv", "streamlit", "altair",
       "vl-convert-python", "yfinance", "playwright", "pytest", "ruff"]  # fmt: skip


def run(*cmd: str) -> str:
    try:
        return subprocess.run(
            cmd, cwd=PROJECT_ROOT, capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "not available"


def main() -> int:
    argparse.ArgumentParser(description=__doc__.splitlines()[0]).parse_args()
    dists = sorted(
        {
            (d.metadata["Name"].lower().replace("_", "-"), d.version)
            for d in importlib.metadata.distributions()
        }
    )
    versions = dict(dists)
    out = [
        "# Environment — software versions behind the results (Phase 10, Step 10.4)",
        "",
        "> Generated by `scripts/record_environment.py`. The exact pins are in `uv.lock` (committed); this file is a",
        "> readable snapshot of the environment the reports were reproduced in.",
        "",
        "| Item | Version |",
        "|---|---|",
        f"| Python | {platform.python_version()} ({platform.python_implementation()}) |",
        f"| uv | {run('uv', '--version').removeprefix('uv ')} |",
        f"| Operating system | {platform.system()} {platform.release()} ({platform.machine()}) |",
        f"| Project package | quantitative-stock-strategy-platform {versions.get('quantitative-stock-strategy-platform', 'not installed')} |",
        f"| Git commit when written | {run('git', 'rev-parse', '--short', 'HEAD')} |",
        "",
        "## Key packages",
        "",
        "| Package | Version |",
        "|---|---|",
        *[f"| {k} | {versions.get(k, 'not installed')} |" for k in KEY],
        "",
        f"## All installed packages ({len(dists)})",
        "",
        ", ".join(f"{n} {v}" for n, v in dists),
        "",
    ]
    REPORT.write_text("\n".join(out), encoding="utf-8")
    print(
        f"written {REPORT.relative_to(PROJECT_ROOT)} ({len(dists)} packages, Python {platform.python_version()})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
