"""Phase 7, Steps 7.1 + 7.2: build reports/screening/indicators_2010-2020.md from saved data only.

Run from the project folder:  uv run python scripts/build_indicators.py
- Financial indicators (7.1): data/raw/sec/*_filed-to-2020-12-31.json (7 companies; SPY is a fund), each fiscal year
  POINT-IN-TIME as of the day after its original 10-K was filed (screening/fundamentals.py).
- Trading indicators (7.2): Tiingo raw files 2008–2020 (2008–2009 only as history for the first 2010 values).
- Descriptive numbers only (derived statistics, no daily prices). No ranking. Nothing dated ≥ 2021-01-01 (D8).
"""

import json
import sys
from datetime import date
from pathlib import Path

import pandas as pd

from quant_research.data.loader import load_prices, load_prices_with_warmup
from quant_research.screening import fundamentals as fu
from quant_research.screening.trading import year_indicators

PROJECT_ROOT = Path(__file__).resolve().parents[1]
SEC_DIR = PROJECT_ROOT / "data" / "raw" / "sec"
REPORT = PROJECT_ROOT / "reports" / "screening" / "indicators_2010-2020.md"
COMPANIES = ["AAPL", "MSFT", "KO", "PG", "XOM", "INTC", "T"]
TICKERS = [*COMPANIES, "SPY"]
YEARS = list(range(2010, 2021))
CODE = {fu.FOUND: "F", fu.FALLBACK: "f", fu.MISSING: "M", fu.CONFLICT: "C"}
SAMPLE = [
    ("AAPL", 2019),
    ("KO", 2019),
]  # raw facts printed for an independent check against the filings
CONCEPT_TAGS = [
    fu.REVENUE,
    fu.NET_INCOME,
    fu.ASSETS,
    fu.OCF,
    fu.CAPEX,
    fu.LIABILITIES,
    fu.CURRENT_ASSETS,
    fu.CURRENT_LIABILITIES,
    fu.EPS,
]


def load_company(t: str) -> tuple[dict, dict]:
    [path] = sorted(SEC_DIR.glob(f"{t}_CIK*_filed-to-2020-12-31.json"))
    meta = json.loads(path.with_name(path.name.replace(".json", ".meta.json")).read_text())
    return json.loads(path.read_text()), meta


def fmt(name: str, v: float | None) -> str:
    if v is None:
        return "MISSING"
    if name in ("operating_cash_flow", "free_cash_flow"):
        return f"{v / 1e6:,.0f}"
    return f"{v:.3f}"


def pct(v: float | None) -> str:
    return "MISSING" if v is None else f"{v:.2%}"


def main() -> int:
    cik_map = json.loads((SEC_DIR / "cik_map.json").read_text())
    out = [
        "# Phase 7 indicators 2010–2020 (Steps 7.1 + 7.2)",
        "",
        "> **Descriptive data for Phase 7 screening — not a recommendation.** Derived accounting and trading",
        "> statistics only (no daily prices). No ranking yet (Step 7.3). Nothing filed or dated after 2020-12-31 is",
        "> used (D8). Generated by `scripts/build_indicators.py` from saved files; no number is typed by hand.",
        "",
        "## 1. Sources and companies",
        "",
        "Financial facts: SEC EDGAR XBRL `companyfacts` API (free, no key; public information — cite SEC as the",
        "source). Facts filed after 2020-12-31 were dropped at download, before saving. CIKs from SEC's official",
        f"ticker list ({cik_map['source']}, a CURRENT snapshot of {cik_map['rows_in_sec_file']:,} rows).",
        "",
        "| Ticker | CIK in SEC's list today | CIK used (2010–2020 filer) | Entity | Facts kept | Facts dropped (filed > 2020-12-31) | Latest filed kept |",
        "|---|---|---|---|---|---|---|",
    ]
    data: dict[str, dict] = {}
    for t in TICKERS:
        listed = cik_map["ciks"][t]
        if t not in COMPANIES:
            out.append(
                f"| {t} | {listed['cik']:010d} | — | {listed['title']} | fund: no company financials, "
                "excluded from 7.1 (kept in 7.2) | — | — |"
            )
            continue
        cf, meta = load_company(t)
        data[t] = cf
        out.append(
            f"| {t} | {listed['cik']:010d} | {meta['cik']:010d} | {meta['entity_name']} | {meta['facts_kept']:,} | "
            f"{meta['facts_dropped_after_cutoff']:,} | {meta['latest_filed_kept']} |"
        )
    out += [
        "",
        "**XOM:** SEC's list today maps XOM to *ExxonMobil Holdings Corp* (CIK 2115436), which filed nothing before",
        "2021 (0 facts kept). The company that filed Exxon's 10-Ks in 2010–2020 is *EXXON MOBIL CORP* (formerly",
        "EXXON CORP), CIK 34088 — checked on SEC's submissions API; used here. A ticker list from today is not a",
        "point-in-time source (Step 7.4).",
        "",
        "## 2. Point-in-time rule and fiscal years",
        "",
        "- A fact is usable on trading day T only if it was **filed strictly before T**. Each fiscal year below is",
        "  shown as of the day after its ORIGINAL 10-K was filed ('usable from').",
        "- Restatements: the latest filing before T wins (first-filed value until a later filing replaces it).",
        "  Two different values filed the same day → CONFLICT (never picked).",
        "- Annual values only: forms 10-K / 10-K/A; durations 350–380 days; balance sheet at the fiscal-year end.",
        "- Fiscal-year end of a 10-K = latest ~1-year period end before its filing date (≤ 180 days), backed by",
        f"  ≥ {fu.MIN_FACTS_FOR_YEAR_END} facts (stray facts dated after the filing are ignored).",
        "- FY2020 10-Ks filed in 2021 (KO, XOM, INTC, T) are NOT available (D8) — those years are absent, not missing.",
        "",
        "## 3. Tag choices (first tag preferred; later tags = fallback, shown as 'f')",
        "",
        "| Item | XBRL tags in priority order | Unit |",
        "|---|---|---|",
    ]
    for c in CONCEPT_TAGS:
        out.append(f"| {c.name} | {' → '.join(f'`{x}`' for x in c.tags)} | {c.unit} |")
    out += [
        (
            "| total liabilities (extra fallbacks) | `LiabilitiesAndStockholdersEquity` − "
            "`StockholdersEquityIncludingPortionAttributableToNoncontrollingInterest`; else "
            "`LiabilitiesAndStockholdersEquity` − `StockholdersEquity` **only if no non-controlling interest is tagged** "
            "(ASSUMPTION: none) | USD |"
        ),
        "",
        "Indicators: net margin = net income ÷ revenue · return on assets = net income ÷ year-end total assets ·",
        "operating cash flow (US$ m) · free cash flow = OCF − capex (US$ m) · FCF margin = FCF ÷ revenue ·",
        "**liabilities to assets** = total liabilities ÷ total assets (chosen over debt-to-equity: debt tags differ a lot",
        "between companies; this ratio includes non-debt liabilities) · current ratio = current assets ÷ current",
        "liabilities · earnings stability = sample std dev of the last 5 yearly diluted-EPS growth rates, each growth",
        "taken from ONE filing that reports both years (so stock splits never mix share bases).",
        "",
    ]
    # coverage + tag usage
    results: dict[str, list[tuple[fu.FiscalYear, dict[str, fu.Indicator]]]] = {}
    tag_use: dict[tuple[str, str], dict[str, int]] = {}
    for t, cf in data.items():
        rows = []
        for fy in fu.fiscal_years(cf):
            if fy.end.year in YEARS:
                ind = fu.indicators_as_of(cf, fy.end, fy.usable_from)
                rows.append((fy, ind))
                seen = set()
                for i in ind.values():
                    for comp in i.components:
                        for f in comp.facts:
                            if (comp.concept, f.tag, f.end) not in seen:
                                seen.add((comp.concept, f.tag, f.end))
                                key = (t, comp.concept)
                                tag_use.setdefault(key, {})
                                tag_use[key][f.tag] = tag_use[key].get(f.tag, 0) + 1
        results[t] = rows
    out += ["**Tags actually used** (number of fiscal-year values per tag):", ""]
    for t in data:
        used = "; ".join(
            f"{concept}: " + ", ".join(f"`{tag}` {n}" for tag, n in tags.items())
            for (tt, concept), tags in tag_use.items()
            if tt == t
            and (len(tags) > 1 or next(iter(tags)) not in {c.tags[0] for c in fu.CONCEPTS})
        )
        out.append(f"- {t}: {used or 'preferred tags only'}")
    out += [
        "",
        "## 4. Coverage (F = found with the preferred tag · f = fallback · M = MISSING · C = CONFLICT · blank = no 10-K)",
        "",
        "Column = calendar year of the fiscal-year END (AAPL ends late Sept; MSFT and PG end 30 June).",
        "",
        "| Company | Indicator | " + " | ".join(str(y) for y in YEARS) + " |",
        "|---|---|" + "---|" * len(YEARS),
    ]
    counts = {s: 0 for s in CODE}
    for t, rows in results.items():
        by_year = {fy.end.year: ind for fy, ind in rows}
        for name in fu.INDICATORS:
            cells = []
            for y in YEARS:
                if y in by_year:
                    s = by_year[y][name].status
                    counts[s] += 1
                    cells.append(CODE[s])
                else:
                    cells.append("")
            out.append(f"| {t} | {name} | " + " | ".join(cells) + " |")
    out += [
        "",
        "Totals: "
        + " · ".join(f"{CODE[s]} {n}" for s, n in counts.items())
        + " (company × indicator × year).",
        "",
        "**Why values are MISSING** (from the data, not guessed):",
        "",
    ]
    reasons: dict[tuple[str, str], list[int]] = {}
    for t, rows in results.items():
        for fy, ind in rows:
            for name, i in ind.items():
                if i.status in (fu.MISSING, fu.CONFLICT):
                    why = (
                        i.note
                        if not i.components
                        else "; ".join(
                            f"{c.concept} {c.status}"
                            for c in i.components
                            if c.status in (fu.MISSING, fu.CONFLICT)
                        )
                        or i.note
                    )
                    if name == "eps_growth_stdev_5y" and "consecutive years" in why:
                        why = "fewer than 6 consecutive years of EPS in XBRL filings so far"
                    reasons.setdefault((t, f"{name}: {why}"), []).append(fy.end.year)
    for (t, why), years in reasons.items():
        out.append(f"- {t} {why} — FY {', '.join(map(str, years))}")
    out += ["", "## 5. Financial indicators per company (as of 'usable from')", ""]
    for t, rows in results.items():
        out += [
            f"**{t}**",
            "",
            (
                "| FY end | 10-K filed | Usable from | Net margin | ROA | OCF US$ m | FCF US$ m | FCF margin | "
                "Liabilities ÷ assets | Current ratio | EPS growth std dev (5y) |"
            ),
            "|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for fy, ind in rows:
            out.append(
                f"| {fy.end} | {fy.filed} | {fy.usable_from} | "
                + " | ".join(fmt(n, ind[n].value) for n in fu.INDICATORS)
                + " |"
            )
        out.append("")
    # trading indicators
    out += [
        "## 6. Trading indicators per year (Tiingo raw data; 2008–2009 rows used only as history)",
        "",
        "Median dollar volume = median of close_raw × volume_raw (US$ m) · volatility = sample std dev of daily",
        "split-aware returns × √252 · daily range = median (high − low) ÷ close · max drawdown within the year on",
        "split-adjusted-as-of-T closes (price only, no dividends) · dividend yield = dividends with ex-date in the 365",
        "days to the year's last trading day (in that day's share units) ÷ that day's close.",
        "**Spreads: not available in free daily data** — only the ASSUMED levels are used elsewhere (tight 0.02% /",
        "normal 0.05% / wide 0.10% per side, EXPERIMENT_PLAN).",
        "",
        "| Ticker | Year | Days | Median $ volume (US$ m) | Volatility | Median daily range | Max drawdown | Dividend yield (TTM) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for t in TICKERS:
        dev = load_prices_with_warmup(t, date(2008, 1, 1), date(2010, 1, 1), date(2016, 12, 31))
        val = load_prices(t, date(2017, 1, 1), date(2020, 12, 31))
        df = pd.concat([dev, val], ignore_index=True)
        if max(df["date"]) >= date(2021, 1, 1) or df["date"].duplicated().any():
            raise SystemExit(f"{t}: unexpected dates (≥ 2021 or duplicated)")
        for y in YEARS:
            r = year_indicators(df, y)
            out.append(
                f"| {t} | {y} | {r.days} | {r.median_dollar_volume_usd / 1e6:,.0f} | {pct(r.volatility_annualised)} | "
                f"{pct(r.median_daily_range)} | {pct(r.max_drawdown)} | {pct(r.dividend_yield_ttm)} |"
            )
    # sample raw facts
    out += [
        "",
        "## Appendix A — raw facts behind every indicator (for checking against the filings)",
        "",
    ]
    for t, year in SAMPLE:
        fy, ind = next((fy, ind) for fy, ind in results[t] if fy.end.year == year)
        out += [
            f"**{t} — fiscal year ending {fy.end}** (10-K {fy.accn}, filed {fy.filed}; usable from {fy.usable_from})",
            "",
            "| Indicator | Item | XBRL tag | Value | Period | Filed | Form | Accession |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for name, i in ind.items():
            for comp in i.components:
                for f in comp.facts:
                    period = f"{f.start} → {f.end}" if f.start else f"at {f.end}"
                    derived = len(comp.facts) > 1 and comp.concept != "EPS pairs"
                    item = f"{comp.concept} (derived — part)" if derived else comp.concept
                    value = f"{f.val:,.2f}" if f.unit == "USD/shares" else f"{f.val:,.0f}"
                    out.append(
                        f"| {name} | {item} | `{f.tag}` | {value} | {period} | {f.filed} | {f.form} | {f.accn} |"
                    )
        out.append("")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(
        f"report written: {REPORT.relative_to(PROJECT_ROOT)} ; coverage "
        + str({CODE[s]: n for s, n in counts.items()})
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
